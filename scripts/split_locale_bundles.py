"""The SPA's UI-string bundles, one file per namespace and language (KAN-616).

Layout: `frontend/apps/dms/src/i18n/locales/<language>/<namespace>.json` holds one top-level
namespace of the bundle (`apiRefusal`, `customerDetail`, ...). A namespace larger than
`MAX_FILE_BYTES` is split by its second level: `<namespace>.<key>.json` holds that one child
object and `<namespace>.json` keeps the rest. `locales/<language>.ts` is generated: it imports
every file of the language (typed, as JSON modules) and assembles the bundle i18next is given,
so `import('./locales/de')` stays one chunk per language (KAN-438) and a test reading
`de.apiRefusal.notFound` keeps its types.

    python3 scripts/split_locale_bundles.py split   # <language>.json -> <language>/<namespace>.json
    python3 scripts/split_locale_bundles.py index   # rewrite every <language>.ts from the files present

`split` is the one-time move (KAN-616); it is idempotent - a language that already has its folder
is left alone. Run `index` after adding or removing a namespace file; `localeKeyParity.test.ts`
fails while a `<language>.ts` misses a file or a language misses a namespace another one has.
"""

import argparse
import json
import sys
from collections.abc import Sequence
from pathlib import Path

LOCALES_DIR = Path(__file__).resolve().parents[1] / "frontend" / "apps" / "dms" / "src" / "i18n" / "locales"
LANGUAGES = ("de", "fr", "it", "en")
# KAN-616 exit criterion 1: no locale file above 25 KB. localeKeyParity.test.ts holds the same number.
MAX_FILE_BYTES = 25_000


def dump(value: object) -> str:
    """The bundles' on-disk form: two-space indent, UTF-8 as is, a final newline."""
    return json.dumps(value, ensure_ascii=False, indent=2) + "\n"


def namespace_files(namespace: str, value: object) -> dict[str, object]:
    """File name -> content for one namespace: one file, or split by its second level when too big."""
    if len(dump(value).encode("utf-8")) <= MAX_FILE_BYTES or not isinstance(value, dict):
        return {f"{namespace}.json": value}
    files: dict[str, object] = {}
    rest = {key: child for key, child in value.items() if not isinstance(child, dict)}
    for key, child in value.items():
        if isinstance(child, dict):
            if "." in key:
                raise SystemExit(f"KAN-616 split: {namespace}.{key} has a dot in its key; split it by hand.")
            files[f"{namespace}.{key}.json"] = child
    if rest:
        files[f"{namespace}.json"] = rest
    for name, content in files.items():
        if len(dump(content).encode("utf-8")) > MAX_FILE_BYTES:
            raise SystemExit(f"KAN-616 split: {name} is still above {MAX_FILE_BYTES} bytes; split it by hand.")
    return files


def split(locales_dir: Path) -> None:
    for language in LANGUAGES:
        legacy = locales_dir / f"{language}.json"
        folder = locales_dir / language
        if folder.is_dir():
            print(f"{language}: {folder.name}/ exists - left alone")
            continue
        bundle = json.loads(legacy.read_text(encoding="utf-8"))
        folder.mkdir()
        written = 0
        for namespace, value in bundle.items():
            for name, content in namespace_files(namespace, value).items():
                (folder / name).write_text(dump(content), encoding="utf-8")
                written += 1
        legacy.unlink()
        print(f"{language}: {len(bundle)} namespaces -> {written} files in {folder.name}/")


def _identifier(name: str) -> str:
    return "ns_" + name.removesuffix(".json").replace(".", "__")


def index_source(folder: Path) -> str:
    names = sorted(path.name for path in folder.glob("*.json"))
    imports = "\n".join(f"import {_identifier(name)} from './{folder.name}/{name}'" for name in names)
    # namespace -> (its own file or None, [second-level keys split into files of their own])
    namespaces: dict[str, tuple[str | None, list[str]]] = {}
    for name in names:
        parts = name.removesuffix(".json").split(".")
        own, subs = namespaces.get(parts[0], (None, []))
        if len(parts) == 1:
            own = name
        elif len(parts) == 2:
            subs.append(parts[1])
        else:
            raise SystemExit(f"KAN-616 index: {folder.name}/{name} - at most <namespace>.<key>.json")
        namespaces[parts[0]] = (own, subs)
    entries = []
    for namespace, (own, subs) in namespaces.items():
        if not subs:
            entries.append(f"  {namespace}: {_identifier(namespace)},")
            continue
        members = ([f"...{_identifier(namespace)}"] if own else []) + [
            f"{sub}: {_identifier(f'{namespace}.{sub}')}" for sub in subs
        ]
        entries.append(f"  {namespace}: {{ {', '.join(members)} }},")
    return (
        f"// Generated by scripts/split_locale_bundles.py (KAN-616) - do not edit by hand. Strings live in\n"
        f"// ./{folder.name}/<namespace>.json; after adding or removing one of those files, run\n"
        f"// `python3 scripts/split_locale_bundles.py index`.\n"
        f"{imports}\n\n"
        f"const bundle = {{\n" + "\n".join(entries) + "\n}\n\nexport default bundle\n"
    )


def index(locales_dir: Path) -> None:
    for language in LANGUAGES:
        folder = locales_dir / language
        target = locales_dir / f"{language}.ts"
        source = index_source(folder)
        if not target.is_file() or target.read_text(encoding="utf-8") != source:
            target.write_text(source, encoding="utf-8")
            print(f"{language}: wrote {target.name}")
        else:
            print(f"{language}: {target.name} up to date")


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("command", choices=("split", "index"))
    parser.add_argument("--locales-dir", type=Path, default=LOCALES_DIR)
    args = parser.parse_args(argv)
    if args.command == "split":
        split(args.locales_dir)
    index(args.locales_dir)
    return 0


if __name__ == "__main__":
    sys.exit(main())
