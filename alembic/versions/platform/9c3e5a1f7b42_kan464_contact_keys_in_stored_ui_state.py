def _move_keys(pairs: Sequence[tuple[str, str, str, str]]) -> None:
    values = ", ".join(
        "(" + ", ".join("'" + part.replace("'", "''") + "'" for part in pair) + ")" for pair in pairs
    )
    op.execute(
        "UPDATE ui_translation AS t SET namespace = m.new_namespace, key = m.new_key"
        f" FROM (VALUES {values}) AS m(old_namespace, old_key, new_namespace, new_key)"
        " WHERE t.namespace = m.old_namespace AND t.key = m.old_key"
        " AND NOT EXISTS (SELECT 1 FROM ui_translation AS u"
        " WHERE u.namespace = m.new_namespace AND u.key = m.new_key AND u.language = t.language)"
    )
    op.execute("UPDATE ui_translation_revision SET version = version + 1, updated_at = now() WHERE scope = 'ui'")


def _renamed(node: Any, names: dict[str, str]) -> Any:
    if isinstance(node, dict):
        return {names.get(key, key): _renamed(value, names) for key, value in node.items()}
    if isinstance(node, list):
        return [_renamed(item, names) for item in node]
    if isinstance(node, str):
        return names.get(node, node)
    return node


def _move_preferences(scopes: Sequence[tuple[str, str]], names: dict[str, str]) -> None:
    if context.is_offline_mode():
        op.execute("-- user_preference step skipped: it reads rows and needs a live database")
        return
    bind = op.get_bind()
    for old, new in scopes:
        bind.execute(
            sa.text(
                "UPDATE user_preference AS p SET scope = :new WHERE scope = :old AND NOT EXISTS"
                " (SELECT 1 FROM user_preference AS q WHERE q.user_id = p.user_id AND q.scope = :new)"
            ),
            {"old": old, "new": new},
        )
    for user_id, scope, payload in bind.execute(sa.text("SELECT user_id, scope, payload FROM user_preference")).all():
        document = json.loads(payload) if isinstance(payload, str) else payload
        moved = _renamed(document, names)
        if moved != document:
            bind.execute(
                sa.text("UPDATE user_preference SET payload = :payload WHERE user_id = :user_id AND scope = :scope"),
                {"payload": json.dumps(moved), "user_id": user_id, "scope": scope},
            )


